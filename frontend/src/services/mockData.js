// Generate mock tee times for a given date
export function generateMockTeeTimes(courseId, date) {
  const teeTimes = [];
  const course = newEnglandCourses.find(c => c.id === parseInt(courseId));
  if (!course) return [];

  for (let hour = 6; hour < 18; hour++) {
    for (let minute = 0; minute < 60; minute += 15) {
      teeTimes.push({
        id: parseInt(`${courseId}${hour}${minute}`),
        course_id: courseId,
        tee_date: date,
        tee_time: `${hour.toString().padStart(2, '0')}:${minute.toString().padStart(2, '0')}:00`,
        available_slots: Math.floor(Math.random() * 4) + 1,
        course_name: course.name,
        price_weekday: course.price_weekday,
        price_weekend: course.price_weekend,
      });
    }
  }
  return teeTimes;
}

// Generate itinerary based on courses and dates
export function generateItinerary(courses, startDate, numDays) {
  const days = [];
  const dayNames = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

  for (let i = 0; i < numDays; i++) {
    const isGolfDay = i === 1 || i === 3 || i === 5; // Golf on days 2, 4, 6
    const courseIndex = Math.floor((i / 2)) % courses.length;

    if (i === 0) {
      days.push({
        day: `Day 1 - Arrival`,
        activity: 'Arrive and check into lodging. Explore the area, grab dinner, and get ready for golf tomorrow.',
      });
    } else if (isGolfDay && courses[courseIndex]) {
      days.push({
        day: `Day ${i + 1} - Golf`,
        activity: `Morning round at ${courses[courseIndex].name}. Afternoon free for exploring or relaxing.`,
      });
    } else if (i === numDays - 1) {
      days.push({
        day: `Day ${i + 1} - Departure`,
        activity: 'Check out and head home. Safe travels!',
      });
    } else {
      days.push({
        day: `Day ${i + 1} - Rest Day`,
        activity: 'Free day to explore local attractions, hike, visit breweries, or just relax.',
      });
    }
  }

  return days;
}

// Mock bookings storage (in-memory for demo)
let mockBookings = [];
let bookingIdCounter = 1;

export const mockBookingsApi = {
  getAll: () => mockBookings,
  create: (teeTime, players, user) => {
    const isWeekend = new Date(teeTime.tee_date).getDay() % 6 === 0;
    const price = isWeekend ? teeTime.price_weekend : teeTime.price_weekday;
    const booking = {
      id: bookingIdCounter++,
      user_id: user?.id || 1,
      tee_time_id: teeTime.id,
      players,
      total_price: price * players,
      status: 'confirmed',
      tee_date: teeTime.tee_date,
      tee_time: teeTime.tee_time,
      course_name: teeTime.course_name,
      created_at: new Date().toISOString(),
    };
    mockBookings.push(booking);
    return booking;
  },
  cancel: (id) => {
    const booking = mockBookings.find(b => b.id === id);
    if (booking) {
      booking.status = 'cancelled';
    }
    return booking;
  },
};

